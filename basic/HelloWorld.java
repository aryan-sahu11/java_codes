public class HelloWorld {
    public static void main(String[] args) {
        System.out.println("Hello, World!");
        // integer
        byte num = 5;
        short n =1;
        int i = 200;
        long l = 2000;
        System.out.println(num +"," +n +"," +i +"," +l);

        // real 
        float f =5.5f;
        double d = 4.4;
        System.out.println(f+"," +d);
    }
}
